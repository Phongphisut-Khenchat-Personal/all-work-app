-- Backfill default boards and attach existing tasks
insert into public.board_columns (team_id, name, position)
select t.id, x.name, x.pos
from public.teams t
cross join (values ('To Do', 0), ('Doing', 1), ('Done', 2)) as x(name, pos)
where not exists (
  select 1 from public.board_columns c where c.team_id = t.id
);

update public.tasks t
set column_id = c.id
from public.board_columns c
where t.column_id is null
  and c.team_id = t.team_id
  and c.position = case t.status
    when 'doing' then 1
    when 'done' then 2
    else 0
  end;

update public.tasks
set created_by = assignee_id
where created_by is null and assignee_id is not null;

