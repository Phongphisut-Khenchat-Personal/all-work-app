-- ---------------------------------------------------------------------------
-- Helpers (security definer — avoids RLS recursion)
-- ---------------------------------------------------------------------------
create or replace function public.is_team_member(tid bigint)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.team_members
    where team_id = tid and user_id = auth.uid()
  );
$$;

create or replace function public.is_team_owner(tid bigint)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.team_members
    where team_id = tid and user_id = auth.uid() and role = 'owner'
  );
$$;

create or replace function public.can_read_profile(pid uuid)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select pid = auth.uid()
  or exists (
    select 1
    from public.team_members tm
    join public.team_members me on me.team_id = tm.team_id
    where tm.user_id = pid and me.user_id = auth.uid()
  );
$$;

