create or replace function public.invite_member_by_email(p_team_id bigint, p_email text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid;
begin
  if not public.is_team_owner(p_team_id) then
    raise exception 'Only the team owner can invite members';
  end if;

  select id into v_user
  from public.profiles
  where lower(email) = lower(trim(p_email));

  if v_user is null then
    raise exception 'User not found. They must sign up first.';
  end if;

  if v_user = auth.uid() then
    raise exception 'You are already in this team';
  end if;

  insert into public.team_members (team_id, user_id, role)
  values (p_team_id, v_user, 'member');
exception
  when unique_violation then
    raise exception 'This user is already a member';
end;
$$;

create or replace function public.leave_team(p_team_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_role text;
begin
  select role into v_role
  from public.team_members
  where team_id = p_team_id and user_id = auth.uid();

  if v_role is null then
    raise exception 'You are not a member of this team';
  end if;

  if v_role = 'owner' then
    raise exception 'Owner cannot leave. Delete the team instead.';
  end if;

  delete from public.team_members
  where team_id = p_team_id and user_id = auth.uid();
end;
$$;

